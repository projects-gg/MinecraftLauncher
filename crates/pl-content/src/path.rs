//! Path safety for paths that come from remote content.
//!
//! Pack manifests and documents are signed, but a compromised Studio key or a bug must still
//! never let content write outside the game directory or into launcher-owned folders. Every
//! remote path is a `/`-separated relative path validated here before it touches the disk or
//! a URL.

use std::path::{Path, PathBuf};

use crate::error::{Error, Result};

/// Longest relative path accepted from remote content, in bytes.
pub const MAX_RELATIVE_PATH: usize = 512;

/// Folder inside a game directory that belongs to the launcher (pack state); packs may not
/// write into it.
pub const LAUNCHER_DIR: &str = ".projects";

/// Validates a relative file path from a pack manifest (or any remote source that maps onto a
/// local directory).
///
/// Rejected: empty or overlong paths, absolute paths, backslashes, `:` (drive letters, NTFS
/// streams), control characters, empty, `.` or `..` components, components ending in a dot or
/// space, characters Windows forbids (`<>"|?*`), Windows device names (`CON`, `nul.txt`,
/// `COM1`, …) and the launcher's own `.projects/` folder.
pub fn check_relative_path(path: &str) -> Result<()> {
    let fail = |reason| Err(Error::unsafe_path(path, reason));
    if path.is_empty() {
        return fail("empty path");
    }
    if path.len() > MAX_RELATIVE_PATH {
        return fail("path is too long");
    }
    if path.starts_with('/') {
        return fail("absolute path");
    }
    if path.contains('\\') {
        return fail("backslash separator");
    }
    if path.contains(':') {
        return fail("drive letter or stream separator");
    }
    if path.chars().any(char::is_control) {
        return fail("control character");
    }
    for (index, component) in path.split('/').enumerate() {
        if component.is_empty() {
            return fail("empty path component");
        }
        if component == "." || component == ".." {
            return fail("relative path component");
        }
        if component.ends_with('.') || component.ends_with(' ') {
            return fail("component ends with a dot or space");
        }
        if component
            .chars()
            .any(|c| matches!(c, '<' | '>' | '"' | '|' | '?' | '*'))
        {
            return fail("character not allowed on Windows");
        }
        if is_windows_device_name(component) {
            return fail("reserved device name");
        }
        if index == 0 && component.eq_ignore_ascii_case(LAUNCHER_DIR) {
            return fail("launcher-owned folder");
        }
    }
    Ok(())
}

/// Validates a path relative to a mirror base URL (documents, media, hosted files). These are
/// generated by Studio, so the alphabet is restricted to `[A-Za-z0-9._-/]` on top of
/// [`check_relative_path`], which keeps URL joining unambiguous.
pub fn check_mirror_path(path: &str) -> Result<()> {
    check_relative_path(path)?;
    if !path
        .bytes()
        .all(|b| b.is_ascii_alphanumeric() || matches!(b, b'.' | b'_' | b'-' | b'/'))
    {
        return Err(Error::unsafe_path(
            path,
            "character not allowed in a mirror path",
        ));
    }
    Ok(())
}

/// Joins a validated relative path onto `base`, component by component.
pub fn join_relative(base: &Path, path: &str) -> Result<PathBuf> {
    check_relative_path(path)?;
    let mut joined = base.to_path_buf();
    joined.extend(path.split('/'));
    Ok(joined)
}

fn is_windows_device_name(component: &str) -> bool {
    // Windows ignores everything after the first dot and trailing spaces: "nul.txt" is NUL.
    let stem = component.split('.').next().unwrap_or(component).trim_end();
    let upper = stem.to_ascii_uppercase();
    match upper.as_str() {
        "CON" | "PRN" | "AUX" | "NUL" | "CONIN$" | "CONOUT$" => true,
        _ => {
            let bytes = upper.as_bytes();
            bytes.len() == 4
                && (upper.starts_with("COM") || upper.starts_with("LPT"))
                && bytes[3].is_ascii_digit()
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn accepts_normal_pack_paths() {
        for path in [
            "mods/sodium-fabric-0.6.0+mc1.21.1.jar",
            "config/sodium-options.json",
            "config/sub dir/x.toml",
            "options.txt",
            "resourcepacks/Faithful 32x.zip",
            "shaderpacks/Complementary_r5.zip",
            "mods/x.jar.disabled",
            "config/.hidden",
            "config/conf.json",
            "config/console.txt",
            "config/com10.txt",
        ] {
            check_relative_path(path).unwrap_or_else(|e| panic!("{path}: {e}"));
        }
    }

    #[test]
    fn rejects_unsafe_paths() {
        for path in [
            "",
            "/etc/passwd",
            "../evil.jar",
            "mods/../../evil.jar",
            "mods/./x.jar",
            "./x.jar",
            "mods//x.jar",
            "mods/",
            "mods\\x.jar",
            "..\\x",
            "C:/Windows/x.dll",
            "C:x",
            "file.txt:stream",
            "\\\\server\\share\\x",
            ".projects/pack-state.json",
            ".PROJECTS/x",
            "con",
            "mods/nul.txt",
            "mods/COM1",
            "mods/lpt9.jar",
            "mods/aux .txt",
            "mods/x.",
            "mods/x ",
            "mods/a\0b",
            "mods/a\nb",
            "mods/a?b.jar",
            "mods/a*b.jar",
        ] {
            assert!(
                check_relative_path(path).is_err(),
                "{path:?} must be rejected"
            );
        }
        assert!(check_relative_path(&"a/".repeat(300)).is_err());
    }

    #[test]
    fn mirror_paths_are_strict() {
        check_mirror_path("config/launcher.0123abcd.json").unwrap();
        check_mirror_path("packs/projects/1.2.0.json").unwrap();
        assert!(check_mirror_path("media/a b.webp").is_err());
        assert!(check_mirror_path("media/a%2e.webp").is_err());
        assert!(check_mirror_path("media/a#b").is_err());
        assert!(check_mirror_path("https://evil.example/x").is_err());
    }

    #[test]
    fn join_builds_nested_paths() {
        let base = Path::new("game");
        assert_eq!(
            join_relative(base, "config/a/b.json").unwrap(),
            base.join("config").join("a").join("b.json")
        );
        assert!(join_relative(base, "../x").is_err());
    }
}
