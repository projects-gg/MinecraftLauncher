const FILL: Record<MarkKind, string> = {
  verified: "text-mark-verified",
  admin: "text-mark-admin",
};

/**
 * A profile mark right of a person's name (SOC-VERIFY): a blue or red rosette with a white check,
 * our own drawing, the same wherever the person shows (launcher, Studio; the overlay, the phone and
 * the forum draw the same shape in their own way). Still: no motion of its own. It names itself
 * (`role="img"` with `label`), so a screen reader says "Ayşe, Doğrulanmış hesap"; a row whose own
 * name is read instead (`aria-label`) says it there. The tooltip (`label`) opens under the pointer;
 * pass `tooltip={false}` where a tooltip would sit on another (a menu row, a tooltip).
 */
export function VerifiedMark({
  kind,
  size = 14,
  label,
  tooltip = true,
  className,
}: {
  kind: MarkKind;
  size?: MarkSize;
  /** "Doğrulanmış hesap" / "Projects yöneticisi" in the interface's language. */
  label: string;
  tooltip?: boolean;
  className?: string;
}) {
  const drawing = DRAWINGS[size];
  const mark = (
    <svg
      role="img"
      aria-label={label}
      focusable="false"
      width={size}
      height={size}
      viewBox={`0 0 ${size} ${size}`}
      data-mark={kind}
      className={cn("verified-mark shrink-0", FILL[kind], className)}
    >
      <path d={drawing.rosette} fill="currentColor" />
      <path
        d={drawing.check}
        fill="none"
        stroke="#fff"
        strokeWidth={drawing.width}
        strokeLinecap="round"
        strokeLinejoin="round"
      />
    </svg>
  );
  if (!tooltip) return mark;
  return (
    <Tooltip content={label}>
      <span className="inline-flex shrink-0">{mark}</span>
    </Tooltip>
  );
}
